##Ejercicio numero 9: Desarrolle un algoritmo donde ingreses la cantidad de dinero en soles y convertirlo a dólares. Imprime el mensaje de la cantidad de dólares calculada

print("CONVERTIDOR DE SOLES A DOLARES")
soles = float(input("Ingresa la cantidad de soles: "))
dolares = soles / 3.35
print(f"La cantidad en dólares es: {dolares:.2f}")