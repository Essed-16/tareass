##Ejercicio numero 1: Ingrese dos números, calcule y muestre las operaciones básicas: suma, resta, producto, división y resto entero de ambos valores

num1 = float(input("Ingrese el primer numero: "))
num2 = float(input("Ingrese el segundo numero: "))
print(f"La suma de los dos numeros es {num1 + num2}")
print(f"La resta de los dos numeros es {num1 - num2}")
print(f"El producto de los dos numeros es {num1 * num2}")
print(f"El resto entero de los dos numeros es {num1 % num2}")